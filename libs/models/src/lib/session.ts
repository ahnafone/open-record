// Player sync + cast session protocol. Shared by the web client, the player
// engine and the server (apps/server) so both sides agree on the wire shape
// and the pure queue helpers.

import type { Track } from '../index';

/** Where playback is happening. A device target is a specific client instance (tab/app launch), not just an install. */
export type SessionTarget =
  | { kind: 'device'; clientId: string; deviceId: string }
  | { kind: 'cast'; castId: string };

/**
 * A track as the session carries it. `entryId` identifies this QUEUE ENTRY,
 * not the song: the same song may legitimately appear twice in one queue.
 */
export interface SessionTrack {
  /** Unique within the session. Generated by the writer; the server rejects duplicates. */
  entryId: string;
  /** Global Track.id, e.g. `catalog:sandman`. */
  id: string;
  providerId: string;
  title: string;
  artist: string;
  album?: string;
  durationSec?: number;
  artUrl?: string;
  /** `remote:` tracks: the page URL + site. Only `url` reaches a MediaPlan, and only after validateUrl. */
  source?: { site: string; url: string; id?: string };
  /** `catalog:` tracks: file name under <WEB_DIR>/catalog/audio/ (server-validated basename). */
  catalogFile?: string;
  /**
   * PC-browser local import that has been uploaded for casting. Set by the
   * client after `POST /cast/uploads`; `planFor` turns it into an `upload` plan.
   */
  uploadId?: string;
  /**
   * `local:` device import. The entry still travels in `order` as metadata so
   * every client's indices agree; its path/URL never does.
   */
  local?: boolean;
}

/** A queue row as a client renders it. */
export interface SessionEntry {
  track: Track;
  entryId: string;
}

export interface SessionState {
  /** Monotonic; bumped by structural changes and by entry/playing/stale report changes. */
  revision: number;
  target: SessionTarget | null;
  /** PLAY ORDER: `order[i]` is what plays at position i. Shuffled queues are stored shuffled. */
  order: SessionTrack[];
  /** Index into `order` of the current entry; -1 when nothing is loaded. */
  cursor: number;
  /** Seconds into the current entry when this state was produced. */
  positionSec: number;
  playing: boolean;
  shuffle: boolean;
  repeat: 'off' | 'all' | 'one';
  /** Entry ids in the order before shuffle was enabled, so it can be restored. */
  baseOrderIds?: string[];
  /**
   * Your Stack: entry ids of the user-added songs that have not played yet, in
   * play order. INVARIANT: they are exactly `order[cursor + 1 .. cursor + stack.length]`
   * (pending stack entries always follow the current entry), so every index into
   * `order` stays valid and older clients still see the true play order. Everything
   * after them is autofill (Keep Spinning). Absent = empty (older servers/clients).
   */
  stack?: string[];
  /**
   * SERVER-SIDE availability only (what the server/Cast cannot play).
   * Device-local availability is a client signal (SessionStore.localUnavailable).
   */
  unavailable?: string[];
  /** Cast volume 0..1, when the target is a cast device. */
  castVolume?: number;
  /**
   * The current cast stream is transcoded (no byte ranges), so a seek restarts
   * the track on the speaker rather than jumping inside it. Clients may show a
   * one-line hint; the server sets it from the relay's stream mode.
   */
  castSeekRestarts?: boolean;
  /**
   * The target has sent no report/poll/WS contact for >90 s. Playback keeps
   * its last `playing`/anchor; controllers show "Not responding" and offer a
   * transfer. Cleared by any target contact. Bumps `revision` when it flips.
   */
  targetStale?: boolean;
  /** Server clock (epoch ms) when this state was produced; clients anchor to it. */
  updatedAt: number;
  /** `clientId` of the last device writer, or `castId`; null only for Cast auto-advance. */
  updatedBy: string | null;
  /** Set when another user's session holds the targeted cast device. */
  castOwner?: { deviceId: string; deviceName: string };
}

export interface SessionDevice {
  /** `clientId`: connection and playback identity (one per tab / app launch). */
  id: string;
  /** Stable per install; shown in labels and used for grouping, never for target identity. Cast rows use the `castId`. */
  deviceId: string;
  name: string;
  platform: 'android' | 'ios' | 'web' | 'cast';
  online: boolean;
  /** Target only: no contact for >90 s (see `SessionState.targetStale`). */
  stale?: boolean;
  lastSeenAt: number;
  /** Cast devices only. */
  castId?: string;
  model?: string;
  capabilities: { cast: boolean; localFiles: boolean };
}

