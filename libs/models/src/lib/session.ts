export type SessionCommand =
  | { type: 'play' }
  | { type: 'pause' }
  | { type: 'toggle' }
  | { type: 'stop' }
  | { type: 'clear' }
  | { type: 'next' }
  | { type: 'previous' }
  | { type: 'seek'; positionSec: number }
  | { type: 'playEntry'; entryId: string }
  | { type: 'playIndex'; index: number }
  | {
      type: 'setQueue';
      order: SessionTrack[];
      cursor: number;
      autoplay: boolean;
      shuffle: boolean;
      baseOrderIds?: string[];
      /**
       * `order` is already in play order (client-shuffled, e.g. restoring a
       * shuffled queue). The server keeps it as given instead of reshuffling.
       */
      shuffled?: boolean;
      /**
       * Pending Your Stack entries. NOT part of `order`: the server places them
       * right after the cursor (in this order) and shuffles only `order`.
       */
      stack?: SessionTrack[];
    }
  | {
      type: 'enqueue';
      tracks: SessionTrack[];
      next: boolean;
      /**
       * true = Your Stack entries: `next` puts them at the FRONT of the stack,
       * otherwise at its END. Absent/false = autofill (Keep Spinning): `next`
       * puts them at the front of autofill (after the stack), otherwise at the end.
       */
      stack?: boolean;
    }
  /** Replace the whole pending Your Stack (used by account sync). Entry ids are kept. */
  | { type: 'setStack'; tracks: SessionTrack[] }
  /** Empty the pending Your Stack, or the autofill part (everything after the stack). */
  | { type: 'clearQueue'; which: 'stack' | 'autofill' }
  | { type: 'remove'; entryId: string }
  | { type: 'move'; from: number; to: number }
  | { type: 'replace'; entryId: string; track: SessionTrack }
  | { type: 'setShuffle'; shuffle: boolean }
  | { type: 'setRepeat'; repeat: 'off' | 'all' | 'one' }
  | { type: 'transfer'; target: SessionTarget }
  | { type: 'takeOver'; castId: string }
  | { type: 'setCastVolume'; volume: number };

/** `device.id` is the clientId; `device.deviceId` is the stable install id. */
export interface SessionHello {
  type: 'hello';
  token: string;
  device: SessionDevice;
}

export interface SessionReportMessage {
  type: 'report';
  /**
   * Why the target is reporting. `tick`/`playing` move the anchor only;
   * `ended` advances once with repeat rules; `native-skip` moves the cursor
   * to `entryId` without advancing again.
   */
  reason: 'tick' | 'playing' | 'ended' | 'native-skip';
  entryId: string;
  positionSec: number;
  playing: boolean;
  durationSec?: number;
}

export type SessionClientMessage =
  | SessionHello
  | { type: 'command'; id: string; command: SessionCommand }
  | SessionReportMessage
  | { type: 'pong'; t0: number };

export interface SessionSnapshot {
  serverTime: number;
  /** The calling client's `clientId` and stable `deviceId`. */
  clientId: string;
  deviceId: string;
  /** Bumped whenever the visible device set changes; lets polls skip unchanged device lists. */
  devicesRevision: number;
  session: SessionState | null;
  devices: SessionDevice[];
}

/**
 * Poll response when the caller's `since` equals `session.revision`. It omits
 * the queue (`order`) but still carries the anchor and the device list (a
 * presence change must not be lost just because playback did not change).
 */
export interface SessionUnchanged {
  unchanged: true;
  revision: number;
  devicesRevision: number;
  serverTime: number;
  positionSec: number;
  playing: boolean;
  updatedAt: number;
  targetStale?: boolean;
  devices: SessionDevice[];
}

export type SessionServerMessage =
  | ({ type: 'welcome' } & SessionSnapshot)
  | { type: 'state'; session: SessionState }
  /** Position/playing only; does not bump `revision`. */
  | {
      type: 'tick';
      revision: number;
      positionSec: number;
      playing: boolean;
      updatedAt: number;
      targetStale?: boolean;
    }
  | { type: 'devices'; devices: SessionDevice[]; devicesRevision: number }
  | { type: 'ack'; id: string; ok: boolean; error?: string; revision?: number }
  | { type: 'ping'; t0: number }
  | { type: 'error'; message: string };

