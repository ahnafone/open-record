/**
 * A random id for a queue entry. `crypto.randomUUID` is unavailable on
 * `http://<lan-ip>` (not a secure context), and the web build runs exactly
 * there, so fall back to 16 random bytes as lowercase hex.
 */
export function newEntryId(): string {
  const c = globalThis.crypto;
  if (typeof c?.randomUUID === 'function') return c.randomUUID();
  if (!c || typeof c.getRandomValues !== 'function') {
    throw new Error('No secure random source available');
  }
  const bytes = new Uint8Array(16);
  c.getRandomValues(bytes);
  return Array.from(bytes, (byte) => byte.toString(16).padStart(2, '0')).join('');
}

/** One per `SessionStore` instance (tab / app launch); never persisted. */
export function newClientId(): string {
  return newEntryId();
}

/** `-1` when there is nothing to select; otherwise a valid index into `order`. */
export function clampCursor(length: number, cursor: number): number {
  if (length <= 0 || !Number.isFinite(cursor) || cursor < 0) return -1;
  if (cursor >= length) return length - 1;
  return Math.trunc(cursor);
}

/** The current position extrapolated from the state's anchor; never negative. */
export function anchoredPosition(
  state: Pick<SessionState, 'positionSec' | 'playing' | 'updatedAt'>,
  now: number,
): number {
  if (!state.playing) return Math.max(0, state.positionSec);
  return Math.max(0, state.positionSec + Math.max(0, now - state.updatedAt) / 1000);
}

/**
 * `natural` = the track ended; `natural:false` = a user pressed next.
 * repeat-one restarts only on a natural end, never on a manual next
 * (matches `PlayerEngine.peek(1)`).
 */
export function nextCursor(
  cursor: number,
  length: number,
  repeat: SessionState['repeat'],
  natural: boolean,
): number {
  if (length <= 0) return -1;
  if (!Number.isFinite(cursor) || cursor < 0 || cursor >= length) return 0;
  if (natural && repeat === 'one') return cursor;
  if (cursor + 1 < length) return cursor + 1;
  if (repeat === 'all') return 0;
  return cursor;
}

/** Restart the entry past PREVIOUS_RESTART_SEC, else move back. */
export function previousCursor(
  cursor: number,
  length: number,
  positionSec: number,
): { cursor: number; restart: boolean } {
  if (length <= 0) return { cursor: -1, restart: false };
  const clamped = clampCursor(length, cursor);
  if (positionSec > PREVIOUS_RESTART_SEC) return { cursor: clamped, restart: true };
  if (clamped > 0) return { cursor: clamped - 1, restart: false };
  return { cursor: clamped, restart: true };
}

/** A re-placed queue: the flat play order, the cursor, and the pending Your Stack ids in play order. */
export interface StackPlacement {
  order: SessionTrack[];
  cursor: number;
  stack: string[];
}

/**
 * Re-establishes the Your Stack invariant: `stack` ids are exactly
 * `order[cursor + 1 .. cursor + stack.length]`.
 *
 * `pending` lists the pending entry ids in play order. Each one is taken out of
 * wherever it sits and placed right after the current entry (`order[cursor]`).
 * Rules:
 * - Unknown and duplicate ids are dropped.
 * - The current entry is never pending: if it is in `pending`, it is dropped.
 * - With no current entry (`cursor` -1 or out of range) and pending entries, the
 *   first pending entry becomes current (cursor 0) and the rest follow it.
 * - With no current entry and nothing pending, `order` is returned unchanged.
 *
 * Pure: `order` is not mutated; entries are shared, not copied.
 */
export function placePendingStack(
  order: readonly SessionTrack[],
  cursor: number,
  pending: readonly string[],
): StackPlacement {
  const byId = new Map<string, SessionTrack>();
  for (const entry of order) {
    if (!byId.has(entry.entryId)) byId.set(entry.entryId, entry);
  }
  const clamped = clampCursor(order.length, cursor);
  const currentId = clamped >= 0 ? order[clamped]?.entryId : undefined;

  const ids: string[] = [];
  const seen = new Set<string>();
  for (const id of pending) {
    if (seen.has(id) || id === currentId || !byId.has(id)) continue;
    seen.add(id);
    ids.push(id);
  }
  const pendingEntries = ids.flatMap((id) => {
    const entry = byId.get(id);
    return entry ? [entry] : [];
  });
  const rest = order.filter((entry) => !seen.has(entry.entryId));

  if (currentId === undefined) {
    if (pendingEntries.length === 0) {
      return { order: [...order], cursor: -1, stack: [] };
    }
    return {
      order: [...pendingEntries, ...rest],
      cursor: 0,
      stack: ids.slice(1),
    };
  }

  const at = rest.findIndex((entry) => entry.entryId === currentId);
  return {
    order: [
      ...rest.slice(0, at + 1),
      ...pendingEntries,
      ...rest.slice(at + 1),
    ],
    cursor: at,
    stack: ids,
  };
}

/**
 * Adds `tracks` to the pending Your Stack (`front`: before the existing pending
 * entries, otherwise after them) and re-places the stack after the cursor. The
 * tracks must not already be in `order` (the caller checks duplicates).
 */
export function insertPendingStack(
  order: readonly SessionTrack[],
  cursor: number,
  stack: readonly string[],
  tracks: readonly SessionTrack[],
  front: boolean,
): StackPlacement {
  const added = tracks.map((entry) => entry.entryId);
  const ids = front ? [...added, ...stack] : [...stack, ...added];
  return placePendingStack([...order, ...tracks], cursor, ids);
}

/** True only for the device target whose `clientId` matches; always false for cast/null. */
export function isThisClient(target: SessionTarget | null, clientId: string): boolean {
  return target?.kind === 'device' && target.clientId === clientId;
}

/**
 * Join a base URL (which may carry a path prefix) and a route path without
 * doubling or dropping slashes. An empty path yields one trailing slash.
 */
export function joinUrl(base: string, path: string): string {
  const trimmedBase = base.replace(/\/+$/, '');
  const trimmedPath = path.replace(/^\/+/, '');
  if (!trimmedBase) return trimmedPath;
  if (!trimmedPath) return `${trimmedBase}/`;
  return `${trimmedBase}/${trimmedPath}`;
}
